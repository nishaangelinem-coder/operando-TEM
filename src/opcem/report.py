def save_figure(fig, name: str, caption: str) -> Dict[str, str]:
    """Write the figure plus a sidecar caption that carries the banner."""
    ensure_dirs()
    png = os.path.join(FIGURES, f"{name}.png")
    pdf = os.path.join(FIGURES, f"{name}.pdf")
    fig.savefig(png)
    fig.savefig(pdf)
    with open(os.path.join(FIGURES, f"{name}.caption.md"), "w") as fh:
        fh.write(f"**{name}** — {caption}\n\n_{SIMULATED_BANNER}_\n\n"
                 f"<sub>git={git_sha()}</sub>\n")
    return {"png": png, "pdf": pdf}
